test('media library uploads can replace a logo and a page image, and restoring survives saves', async ({ page }) => {
  await signIn(page)
  await page.goto('/en/admin/media')
  const uploads = page.locator('.library__filters').getByRole('button', { name: /^Uploads/ })
  await uploads.click()
  const before = await page.locator('.library__grid > li').count()
  await page.locator('.library input[type=file]').setInputFiles(['public/logos/partners/nahdi.png'])
  await uploads.click()
  await expect(page.locator('.library__grid > li')).toHaveCount(before + 1)
  await expect(page.locator('.library__grid > li').first()).toContainText('Not used')

  await page.locator('.media-tabs').getByRole('button', { name: 'Logos' }).click()
  const zoa = page.locator('.logo').filter({ hasText: 'Zoā' })
  await zoa.getByRole('button', { name: /Choose from library/ }).click()
  const picker = page.getByRole('dialog', { name: 'Choose a logo for “Zoā”' })
  await picker.getByRole('button', { name: 'Uploads', exact: true }).click()
  await picker.locator('.picker__item').first().click()
  await expect(picker).toBeHidden()
  await expect(zoa).toContainText('Changed, not saved')
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Draft saved')
  await page.reload()
  await expect(zoa).toContainText('Replaced')
  expect(await zoa.locator('img').evaluate(image => (image as HTMLImageElement).naturalWidth > 0)).toBe(true)
  await zoa.getByRole('button', { name: /Restore original/ }).click()
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Draft saved')
  await expect(zoa).not.toContainText('Replaced')

  await page.goto('/en/admin/pages?page=about&tab=images')
  await page.getByRole('button', { name: 'Replace About — hero', exact: true }).click()
  await page.getByRole('button', { name: 'Choose from library', exact: true }).click()
  const photos = page.getByRole('dialog', { name: 'Choose an image for “About — hero”' })
  await photos.getByRole('button', { name: 'Site photos', exact: true }).click()
  await photos.locator('.picker__item:not([disabled])').first().click()
  await expect(photos).toBeHidden()
  const replacer = page.getByRole('dialog', { name: 'Replace “About — hero”' })
  await expect(replacer.locator('.frame img')).toHaveCount(2)
  await replacer.locator('.replacer__foot').getByRole('button', { name: 'Close' }).click()
  await expect(page.locator('.card').filter({ hasText: 'About — hero' })).toContainText('Replacement ready')
  await page.getByRole('button', { name: 'Restore About — hero', exact: true }).click()
  await expect(page.locator('.card').filter({ hasText: 'About — hero' })).not.toContainText('Replacement ready')
})

