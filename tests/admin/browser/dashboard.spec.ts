import { test, expect, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

async function signIn(page: Page) {
  const credentials = JSON.parse(readFileSync('.data/admin-browser-credentials.json', 'utf8'))
  await page.goto('/en/admin/login')
  await page.locator('#login-email').fill(credentials.email)
  await page.locator('#login-password').fill(credentials.password)
  await page.locator('button[type=submit]').click()
  await expect(page.locator('.admin')).toBeVisible()
}
test('all dashboard pages render in English and Arabic without hydration errors or page overflow', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', (message) => {
    if (message.type() === 'error' || /hydration/i.test(message.text())) errors.push(message.text())
  })
  await signIn(page)
  for (const locale of ['en', 'ar']) {
    for (const path of ['', '/pages', '/contact-info', '/brands', '/team', '/enquiries', '/media', '/media?tab=logos']) {
      const response = await page.goto(`/${locale}/admin${path}`)
      expect(response?.status()).toBe(200)
      await expect(page.locator('.admin')).toBeVisible()
      await expect(page.locator('h1')).toHaveCount(1)
      await expect(page.locator('html')).toHaveAttribute('dir', locale === 'ar' ? 'rtl' : 'ltr')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1)).toBe(true)
    }
  }
  expect(errors).toEqual([])
  await page.goto('/ar/admin')
  await page.screenshot({ path: `.data/${info.project.name}-ar.png`, fullPage: true })
})
test('page copy survives navigation and reload; saving and publishing stay separate', async ({ page, context }) => {
  await signIn(page)
  await page.getByRole('link', { name: 'Page content', exact: true }).click()
  const field = page.getByRole('textbox', { name: 'Opening section — Main heading — English', exact: true })
  const original = await field.inputValue()
  const value = `Reviewed heading ${Date.now()}`
  await field.fill(value)
  await expect(page.locator('.workspace-bar')).toHaveAttribute('data-state', 'unsaved')
  await page.getByRole('link', { name: 'Contact details', exact: true }).click()
  await page.getByRole('link', { name: 'Page content', exact: true }).click()
  await expect(field).toHaveValue(value)
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Draft saved')
  await page.reload()
  await expect(field).toHaveValue(value)
  const visitor = await context.newPage()
  await visitor.goto('/en')
  await expect(visitor.locator('h1')).not.toContainText(value)
  const previewPromise = context.waitForEvent('page')
  await page.getByRole('link', { name: 'Preview saved draft' }).click()
  const preview = await previewPromise
  await expect(preview.locator('h1')).toContainText(value)
  await expect(preview.getByText('Saved draft preview — unpublished')).toBeVisible()
  await preview.close()
  await page.getByRole('button', { name: 'Publish changes', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm publication', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('now live')
  await visitor.reload()
  await expect(visitor.locator('h1')).toContainText(value)
  const fromLogin = await context.newPage()
  await fromLogin.goto('/en/admin/login')
  await fromLogin.locator('.login__brand').click()
  await expect(fromLogin.locator('h1')).toContainText(value)
  await fromLogin.close()
  await field.fill(original)
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Draft saved')
  await page.getByRole('button', { name: 'Publish changes', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm publication', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('now live')
  await visitor.close()
})
test('two tabs cannot overwrite each other; failed saves keep local input', async ({ page, context }) => {
  await signIn(page)
  await page.goto('/en/admin/pages')
  const other = await context.newPage()
  await other.goto('/en/admin/pages')
  const field = (page: Page) => page.getByRole('textbox', { name: 'Opening section — Main heading — English', exact: true })
  const original = await field(page).inputValue()
  await field(page).fill('First tab draft')
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Draft saved')
  await field(other).fill('Second tab unsaved text')
  await other.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(other.getByRole('alert')).toContainText('newer version')
  await expect(field(other)).toHaveValue('Second tab unsaved text')
  await other.close()
  await field(page).fill(original)
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Draft saved')
})
